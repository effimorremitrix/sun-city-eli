/* ------------------------------------------------------------------
 * מודעות מהשוק: "מתיווך" רק עם ראיה.
 *
 * עד כה כל מודעה מקומו סומנה 'agency' גורף (בסריקה ובבקפיל של
 * 20260917100000), ומודעות יד2 ממסלולי פלטינום/טריו סומנו 'agency' גם בלי
 * שם משרד. קומו מפרסם גם מודעות של מוכרים פרטיים, והמשרד אינו רשאי להציג
 * אותן. הרשומות האלה חוזרות ל-'unknown' — ולכן מוסתרות מהלקוחות — עד
 * שהסריקה הבאה תסווג אותן מחדש לפי הכללים המחמירים (סימן תיווך/פרטי
 * בכרטיס, או שם משרד בפיד). מודעה עם שם משרד נשארת כפי שהיא.
 * ------------------------------------------------------------------ */
UPDATE public.market_listings
   SET advertiser_type = 'unknown'
 WHERE advertiser_type = 'agency'
   AND agency_name IS NULL
   AND (
     source IN ('komo', 'yad2', 'קומו', 'יד2')
     OR source_site IN ('קומו', 'יד2')
   );
